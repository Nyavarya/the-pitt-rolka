const allCharacters = [...mainCharacters, ...secondaryCharacters];

function getTelegram(character) {
    return character.telegram || '';
}

let currentFilter = 'all';
const charactersContainer1 = document.getElementById('charactersContainer1');
const charactersContainer2 = document.getElementById('charactersContainer2');

function renderMainCharacters(filter = 'all') {
    charactersContainer1.innerHTML = '';
    const filtered = filter === 'all' ? mainCharacters : mainCharacters.filter(c => c.category === filter);
    if (filtered.length === 0) {
        charactersContainer1.innerHTML = `<div class="empty-message"><i class="fas fa-smile-wink"></i><h3>Упс :)</h3><p>Кажется, тут никого нет</p></div>`;
        return;
    }
    filtered.forEach(character => charactersContainer1.appendChild(createCharacterCard(character)));
}

function renderSecondaryCharacters(filter = 'all') {
    charactersContainer2.innerHTML = '';
    const filtered = filter === 'all' ? secondaryCharacters : secondaryCharacters.filter(c => c.category === filter);
    if (filtered.length === 0) {
        charactersContainer2.innerHTML = `<div class="empty-message"><i class="fas fa-smile-wink"></i><h3>Упс :)</h3><p>Кажется, тут никого нет</p></div>`;
        return;
    }
    filtered.forEach(character => charactersContainer2.appendChild(createCharacterCard(character)));
}

function renderAllCharacters(filter = 'all') {
    currentFilter = filter;
    renderMainCharacters(filter);
    renderSecondaryCharacters(filter);
}

function createCharacterCard(character) {
    const card = document.createElement('div');
    card.className = 'character-card';
    const name = character.name && character.name.trim() !== "" ? character.name : "Персонаж";
    const role = character.role && character.role.trim() !== "" ? character.role : "Роль неизвестна";
    const desc = character.description && character.description !== "М" ? 
        (character.description.length > 120 ? character.description.substring(0, 120) + '...' : character.description) 
        : "Информация о персонаже отсутствует...";
    
    const telegram = getTelegram(character);
    const telegramHtml = telegram ? 
        `<div class="character-nickname"><i class="fab fa-telegram"></i><span>${telegram}</span></div>` : 
        `<div class="character-nickname empty"><i class="fab fa-telegram"></i><span>Telegram не указан</span></div>`;
    
    card.innerHTML = `
        <div class="character-image"><img src="${character.image}" alt="${name}" onerror="this.src='https://images.unsplash.com/photo-1559839734-2b71ea197ec2?w=400'"></div>
        <div class="character-info">
            <div class="character-name"><span>${name}</span><i class="fas fa-chevron-right"></i></div>
            <div class="character-role">${role}</div>
            <p class="character-desc">${desc}</p>
            ${telegramHtml}
        </div>
    `;
    card.addEventListener('click', () => openCharacterModal(character));
    return card;
}

const characterModal = document.getElementById('characterModal');
const closeModal = document.getElementById('closeModal');

function openCharacterModal(character) {
    document.getElementById('modalCharacterName').textContent = character.name || "Персонаж";
    document.getElementById('modalCharacterRole').textContent = character.role || "Роль неизвестна";
    document.getElementById('modalCharacterDesc').textContent = character.description || "Информация о персонаже отсутствует.";
    document.getElementById('modalCharacterMedical').textContent = character.medicalAnalysis || "Информация об отношениях отсутствует.";
    
    const telegram = getTelegram(character);
    document.getElementById('modalCharacterPlot').textContent = telegram ? `Telegram: ${telegram}` : 'Telegram: не указан';
    
    document.getElementById('modalCharacterImage').src = character.image;
    document.getElementById('modalCharacterImage').alt = character.name || "Персонаж";
    characterModal.classList.add('active');
    document.body.style.overflow = 'hidden';
}

function closeCharacterModal() {
    characterModal.classList.remove('active');
    document.body.style.overflow = 'auto';
}

const page1 = document.getElementById('page1');
const page2 = document.getElementById('page2');
const page1Btn = document.getElementById('page1Btn');
const page2Btn = document.getElementById('page2Btn');

function showPage1() {
    page1.classList.add('active');
    page2.classList.remove('active');
    page1Btn.classList.add('active');
    page2Btn.classList.remove('active');
    renderMainCharacters(currentFilter);
}

function showPage2() {
    page2.classList.add('active');
    page1.classList.remove('active');
    page2Btn.classList.add('active');
    page1Btn.classList.remove('active');
    renderSecondaryCharacters(currentFilter);
}

function filterCharacters(category) {
    document.querySelectorAll('.filter-btn').forEach(btn => btn.classList.remove('active'));
    document.querySelector(`.filter-btn[data-filter="${category}"]`).classList.add('active');
    renderAllCharacters(category);
}

document.addEventListener('DOMContentLoaded', () => {
    renderAllCharacters('all');
    
    page1Btn.addEventListener('click', showPage1);
    page2Btn.addEventListener('click', showPage2);
    closeModal.addEventListener('click', closeCharacterModal);
    characterModal.addEventListener('click', (e) => {
        if (e.target === characterModal) closeCharacterModal();
    });
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape' && characterModal.classList.contains('active')) closeCharacterModal();
    });
});

window.filterCharacters = filterCharacters;

